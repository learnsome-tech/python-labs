print('a', 'b', 'c')
#   a b c
print('a', 'b', 'c', sep='-')
#   a-b-c
print('a', 'b', end='!')
#   a b!
print('a', 'b', sep='-', end='!')
#   a-b!
print('a', 'b', end='!', sep='-')
#   a-b!
